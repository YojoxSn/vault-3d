import { buildGraph, isIgnoredPath } from '../parser/core';
import type { ContentMap, GraphData, RawFile } from '../parser/types';

export interface Loaded { graph: GraphData; content: ContentMap }
export interface PickedFile { file: File; path: string }

async function getJson<T>(url: string): Promise<T | null> {
  try {
    const r = await fetch(url);
    if (!r.ok || !(r.headers.get('content-type') ?? '').includes('json')) return null;
    return (await r.json()) as T;
  } catch { return null; }
}

export async function loadDemo(): Promise<Loaded> {
  const [graph, content] = await Promise.all([getJson<GraphData>('./demo/graph.json'), getJson<ContentMap>('./demo/content.json')]);
  if (!graph || !content) throw new Error('Demo data not found');
  return { graph, content };
}

/** Graph generated by `npm run build:graph` (dev only: public/graph.json is git-ignored). */
export async function loadLocal(): Promise<Loaded | null> {
  const graph = await getJson<GraphData>('./graph.json');
  if (!graph) return null;
  const content = (await getJson<ContentMap>('./content.json')) ?? {};
  return { graph, content };
}

/** Reads markdown files in the browser. Nothing is uploaded anywhere. */
export async function loadFromFiles(files: PickedFile[], vaultName: string, onProgress?: (done: number, total: number) => void): Promise<Loaded> {
  const md = files.filter((f) => /\.md$/i.test(f.path) && !isIgnoredPath(f.path) && f.file.size < 4_000_000);
  const raw: RawFile[] = [];
  let done = 0, skipped = 0;
  for (let i = 0; i < md.length; i += 16) {
    const batch = md.slice(i, i + 16);
    // A single unreadable file (e.g. an iCloud placeholder that is not downloaded) must not break the whole vault
    const texts = await Promise.all(batch.map((b) => b.file.text().catch(() => null)));
    batch.forEach((b, k) => {
      const t = texts[k];
      if (t === null) skipped++;
      else raw.push({ path: b.path, content: t, mtime: b.file.lastModified });
    });
    done += batch.length;
    onProgress?.(done, md.length);
  }
  if (skipped) console.warn(`[vault3d] ${skipped} file(s) could not be read and were skipped`);
  if (!raw.length) throw new Error(skipped ? `None of the ${skipped} notes could be read (are they downloaded locally?).` : 'No markdown notes found in this folder.');
  const { graph, content } = buildGraph(raw, vaultName, { openable: true });
  return { graph, content };
}

/** From <input webkitdirectory>: paths look like "Vault/Folder/Note.md". */
export function filesFromInput(list: FileList): { files: PickedFile[]; vaultName: string } {
  const arr = Array.from(list);
  const first = (arr[0] as File & { webkitRelativePath?: string })?.webkitRelativePath ?? '';
  const vaultName = first.split('/')[0] || 'Vault';
  const files = arr.map((file) => {
    const rel = (file as File & { webkitRelativePath?: string }).webkitRelativePath || file.name;
    return { file, path: rel.split('/').slice(1).join('/') || file.name };
  });
  return { files, vaultName };
}

type FsEntry = { isFile: boolean; isDirectory: boolean; name: string; file?: (cb: (f: File) => void, err: (e: unknown) => void) => void; createReader?: () => { readEntries: (cb: (e: FsEntry[]) => void, err: (e: unknown) => void) => void } };

/** From a drag & drop: walks the dropped folder, skipping .obsidian, .git, node_modules… */
export async function filesFromDrop(dt: DataTransfer): Promise<{ files: PickedFile[]; vaultName: string } | null> {
  const items = Array.from(dt.items ?? []);
  const roots = items.map((it) => (it as DataTransferItem & { webkitGetAsEntry?: () => FsEntry | null }).webkitGetAsEntry?.()).filter(Boolean) as FsEntry[];
  const dir = roots.find((r) => r.isDirectory);
  if (!dir) return null;
  const out: PickedFile[] = [];
  const walk = async (e: FsEntry, prefix: string): Promise<void> => {
    if (e.isFile) {
      if (!/\.md$/i.test(e.name)) return;
      const file = await new Promise<File>((res, rej) => e.file!(res, rej));
      out.push({ file, path: prefix + e.name });
    } else if (e.isDirectory) {
      if (isIgnoredPath(e.name)) return;
      const reader = e.createReader!();
      for (;;) {
        const batch = await new Promise<FsEntry[]>((res, rej) => reader.readEntries(res, rej));
        if (!batch.length) break;
        for (const child of batch) await walk(child, prefix + e.name + '/');
      }
    }
  };
  const reader = dir.createReader!();
  for (;;) {
    const batch = await new Promise<FsEntry[]>((res, rej) => reader.readEntries(res, rej));
    if (!batch.length) break;
    for (const child of batch) await walk(child, '');
  }
  return { files: out, vaultName: dir.name };
}
